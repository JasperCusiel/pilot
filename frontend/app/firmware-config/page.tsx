'use client';

import { useEffect, useState } from 'react';
import Header from '../components/Header';
import { Card } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Download, Info } from 'lucide-react';

interface JointRow {
  label: string;
  fullStepsPerRev: number;
  microstepping: number;
  gearRatio: number; // e.g. 20 for a 20:1 reduction. 1 = direct drive.
  directionInverted: boolean;
  enableActiveLow: boolean;
  homeActiveLow: boolean;
  homeDirection: 1 | -1;
  limitMinDeg: number;
  limitMaxDeg: number;
  homeBackoffDeg: number;
  homeFastDegPerSec: number;
  homeSlowDegPerSec: number;
  maxSpeedDegPerSec: number;
  accelDegPerSec2: number;
}

const DEFAULT_ROW = (label: string): JointRow => ({
  label,
  fullStepsPerRev: 200,
  microstepping: 16,
  gearRatio: 1,
  directionInverted: false,
  enableActiveLow: true,
  homeActiveLow: true,
  homeDirection: -1,
  limitMinDeg: -180,
  limitMaxDeg: 180,
  homeBackoffDeg: 2,
  homeFastDegPerSec: 15,
  homeSlowDegPerSec: 4,
  maxSpeedDegPerSec: 90,
  accelDegPerSec2: 400,
});

const STORAGE_KEY = 'firmwareConfigDraft.v1';

function stepsPerDegree(row: JointRow): number {
  return (row.fullStepsPerRev * row.microstepping * row.gearRatio) / 360;
}

function generateHeader(rows: JointRow[]): string {
  const jointBlocks = rows.map((row, i) => {
    const spd = stepsPerDegree(row);
    const minSteps = Math.round(row.limitMinDeg * spd);
    const maxSteps = Math.round(row.limitMaxDeg * spd);
    const backoffSteps = Math.round(Math.abs(row.homeBackoffDeg) * spd);
    const homeFastSps = (row.homeFastDegPerSec * spd).toFixed(2);
    const homeSlowSps = (row.homeSlowDegPerSec * spd).toFixed(2);
    const maxSps = (row.maxSpeedDegPerSec * spd).toFixed(2);
    const accelSps2 = (row.accelDegPerSec2 * spd).toFixed(1);
    return `        {${row.directionInverted}, ${row.enableActiveLow}, ${row.homeActiveLow}, ${row.homeDirection}, ` +
      `${minSteps}, ${maxSteps}, 0, ${backoffSteps},\n` +
      `         ${homeFastSps}f, ${homeSlowSps}f, ${maxSps}f, ${accelSps2}f, ${spd.toFixed(3)}f}, // ${row.label}`;
  });

  return `#pragma once

#include <Arduino.h>

// Generated by pilot's Firmware Config page (Configuration > Firmware Config)
// from per-joint reduction ratios and degree/deg-per-second limits.
//
// This ONLY replaces the JointConfig JOINT[] table below. Pin assignments,
// I2S timing, and E-stop wiring are PCB/wiring-specific - copy those
// sections from your existing include/robot_config.h, or from the
// firmware repo's shipped default, unchanged unless you've rewired
// something. See the firmware README's "Read this before powering motors"
// before flashing this.

namespace config {

constexpr uint8_t JOINT_COUNT = 6;
constexpr uint32_t COMMANDER_BAUD = 3000000;

// --- Copy these from your current robot_config.h if they're already ---
// --- correct for your wiring (pins are fixed by the PCB/your wiring) ---
constexpr int I2S_WS_PIN = 26;
constexpr int I2S_BCK_PIN = 25;
constexpr int I2S_DATA_PIN = 27;
constexpr uint8_t STEP_BIT[5]   = {1, 4, 7, 10, 13};
constexpr uint8_t DIR_BIT[5]    = {2, 5, 8, 11, 14};
constexpr uint8_t ENABLE_BIT[5] = {0, 3, 6, 9, 12};
constexpr uint8_t ONBOARD_SOCKET_JOINT[5] = {0, 2, 3, 4, 5};
constexpr uint8_t EXTERNAL_JOINT = 1;
constexpr int EXTERNAL_STEP_PIN = 16;
constexpr int EXTERNAL_DIR_PIN = 17;
constexpr int EXTERNAL_ENABLE_PIN = 15;
constexpr int HOME_PIN[JOINT_COUNT] = {33, 32, 22, 35, 34, 39};
constexpr bool ESTOP_ENABLED = true;
constexpr int ESTOP_PIN = 147;
constexpr bool ESTOP_ACTIVE_LOW = true;
constexpr uint8_t FAN1_BIT = 19;
constexpr uint8_t FAN1_DUTY = 0;
constexpr uint32_t FAN_PWM_HZ = 1000;
constexpr int INPUT_PIN[2] = {-1, -1};
constexpr int OUTPUT_PIN[2] = {-1, -1};
constexpr uint32_t I2S_SAMPLE_RATE = 250000;
constexpr uint32_t EXTERNAL_TICK_RATE = 100000;
constexpr uint32_t CONTROL_RATE = 1000;
constexpr uint32_t HOME_TIMEOUT_MS = 45000;

struct JointConfig {
  bool direction_inverted;
  bool enable_active_low;
  bool home_active_low;
  int8_t home_direction;
  int32_t minimum_steps;
  int32_t maximum_steps;
  int32_t home_position_steps;
  uint32_t home_backoff_steps;
  float home_fast_steps_per_second;
  float home_slow_steps_per_second;
  float maximum_steps_per_second;
  float acceleration_steps_per_second2;
  float steps_per_degree;
};

// --- Generated from your reduction ratios/limits below ---
constexpr JointConfig JOINT[JOINT_COUNT] = {
${jointBlocks.join('\n')}
};

}  // namespace config
`;
}

export default function FirmwareConfigPage() {
  const [rows, setRows] = useState<JointRow[]>(() =>
    ['J1', 'J2', 'J3', 'J4', 'J5', 'J6'].map((l) => DEFAULT_ROW(l))
  );
  const [loadedDraft, setLoadedDraft] = useState(false);

  // Load any saved draft once on mount (pure convenience, this is a real
  // deployed app so localStorage is fine here - just per-browser, not
  // synced anywhere).
  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        setRows(JSON.parse(saved));
        setLoadedDraft(true);
      }
    } catch {
      // ignore corrupt/missing draft
    }
  }, []);

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(rows));
    } catch {
      // storage full/unavailable - not critical, just skip saving the draft
    }
  }, [rows]);

  const updateRow = (i: number, field: keyof JointRow, value: any) => {
    setRows((prev) => {
      const next = [...prev];
      next[i] = { ...next[i], [field]: value };
      return next;
    });
  };

  const handleDownload = () => {
    const content = generateHeader(rows);
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'robot_config.h';
    a.click();
    URL.revokeObjectURL(url);
  };

  const numberField = (
    i: number,
    field: keyof JointRow,
    label: string,
    step = 1
  ) => (
    <div>
      <label className="text-[10px] text-muted-foreground block mb-0.5">{label}</label>
      <input
        type="number"
        step={step}
        value={rows[i][field] as number}
        onChange={(e) => updateRow(i, field, parseFloat(e.target.value) || 0)}
        className="w-full h-7 px-1.5 rounded border bg-background text-xs"
      />
    </div>
  );

  return (
    <main className="h-screen flex flex-col bg-background">
      <Header />
      <div className="flex-1 overflow-auto p-4">
        <div className="max-w-5xl mx-auto space-y-4">
          <Card className="p-4">
            <h1 className="text-lg font-bold mb-1">Firmware Config Generator</h1>
            <p className="text-sm text-muted-foreground mb-2">
              The serial protocol already sends angle-equivalent values to the firmware -
              the firmware converts those to real motor steps using{' '}
              <code className="text-xs bg-muted px-1 rounded">include/robot_config.h</code>'s
              per-joint settings on its own side. This page fills in that table from your
              arm's actual motor/gearing specs instead of hand-computing steps, and generates
              a ready-to-flash header file.
            </p>
            <div className="flex items-start gap-2 text-xs bg-blue-50 border border-blue-200 text-blue-900 rounded-md p-2.5">
              <Info className="h-4 w-4 shrink-0 mt-0.5" />
              <span>
                This only replaces the <code>JOINT[]</code> table in <code>robot_config.h</code> - pin
                assignments and E-stop wiring stay as shown (copy them from your current file if
                you've changed them). After downloading, drop the file into the firmware repo's{' '}
                <code>include/</code> folder, review it, and reflash via PlatformIO. Go through the
                firmware README's "Read this before powering motors" section and test each joint
                at low speed before trusting it.
              </span>
            </div>
            {loadedDraft && (
              <p className="text-[11px] text-muted-foreground mt-2">
                Restored your last draft from this browser.
              </p>
            )}
          </Card>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
            {rows.map((row, i) => {
              const spd = stepsPerDegree(row);
              return (
                <Card key={i} className="p-3">
                  <div className="flex items-center justify-between mb-2">
                    <h2 className="text-sm font-semibold">{row.label}</h2>
                    <span className="text-[10px] text-muted-foreground font-mono">
                      {spd.toFixed(2)} steps/deg
                    </span>
                  </div>

                  <div className="grid grid-cols-3 gap-2 mb-2">
                    {numberField(i, 'fullStepsPerRev', 'Motor full steps/rev')}
                    {numberField(i, 'microstepping', 'Microstepping')}
                    {numberField(i, 'gearRatio', 'Gear/belt ratio (e.g. 20 = 20:1)', 0.01)}
                  </div>

                  <div className="grid grid-cols-2 gap-2 mb-2">
                    {numberField(i, 'limitMinDeg', 'Limit min (deg)')}
                    {numberField(i, 'limitMaxDeg', 'Limit max (deg)')}
                  </div>

                  <div className="grid grid-cols-2 gap-2 mb-2">
                    {numberField(i, 'maxSpeedDegPerSec', 'Max speed (deg/s)')}
                    {numberField(i, 'accelDegPerSec2', 'Acceleration (deg/s²)')}
                  </div>

                  <div className="grid grid-cols-3 gap-2 mb-2">
                    {numberField(i, 'homeFastDegPerSec', 'Home fast (deg/s)')}
                    {numberField(i, 'homeSlowDegPerSec', 'Home slow (deg/s)')}
                    {numberField(i, 'homeBackoffDeg', 'Home backoff (deg)')}
                  </div>

                  <div className="grid grid-cols-2 gap-2 mb-2">
                    <div>
                      <label className="text-[10px] text-muted-foreground block mb-0.5">Home direction</label>
                      <select
                        value={row.homeDirection}
                        onChange={(e) => updateRow(i, 'homeDirection', parseInt(e.target.value) as 1 | -1)}
                        className="w-full h-7 px-1.5 rounded border bg-background text-xs"
                      >
                        <option value={-1}>-1 (toward min)</option>
                        <option value={1}>+1 (toward max)</option>
                      </select>
                    </div>
                    <div className="flex flex-col justify-end gap-1">
                      <label className="flex items-center gap-1.5 text-[11px]">
                        <input
                          type="checkbox"
                          checked={row.directionInverted}
                          onChange={(e) => updateRow(i, 'directionInverted', e.target.checked)}
                        />
                        Direction inverted
                      </label>
                    </div>
                  </div>

                  <div className="flex gap-3">
                    <label className="flex items-center gap-1.5 text-[11px]">
                      <input
                        type="checkbox"
                        checked={row.enableActiveLow}
                        onChange={(e) => updateRow(i, 'enableActiveLow', e.target.checked)}
                      />
                      Enable active-low
                    </label>
                    <label className="flex items-center gap-1.5 text-[11px]">
                      <input
                        type="checkbox"
                        checked={row.homeActiveLow}
                        onChange={(e) => updateRow(i, 'homeActiveLow', e.target.checked)}
                      />
                      Home switch active-low
                    </label>
                  </div>
                </Card>
              );
            })}
          </div>

          <Button onClick={handleDownload} className="w-full h-9">
            <Download className="h-4 w-4 mr-2" />
            Download robot_config.h
          </Button>
        </div>
      </div>
    </main>
  );
}
